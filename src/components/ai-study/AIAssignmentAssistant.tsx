import React, { useState } from 'react';
import {
  CheckSquare,
  Sparkles,
  ListOrdered,
  Calendar,
  Clock,
  FileText,
  AlertTriangle,
  Plus,
  Bookmark,
  CheckCircle2,
} from 'lucide-react';
import { StudyAssignment, AIProposedAction } from '../../types/index.ts';
import {
  runAssignmentAssistant,
  AssignmentBreakdownResponse,
  executeAIProposedAction,
  saveUserAIMaterial,
} from '../../services/aiStudyService.ts';
import { AIActionConfirmationModal } from './AIActionConfirmationModal.tsx';

interface AIAssignmentAssistantProps {
  userId: string;
  assignments: StudyAssignment[];
  onSuccessToast?: (msg: string) => void;
}

export const AIAssignmentAssistant: React.FC<AIAssignmentAssistantProps> = ({
  userId,
  assignments,
  onSuccessToast,
}) => {
  const [selectedAssignmentId, setSelectedAssignmentId] = useState<string>(
    assignments[0]?.id || ''
  );
  const [actionType, setActionType] = useState<
    'breakdown' | 'checklist' | 'work-sequence' | 'effort-estimate' | 'milestones' | 'outline'
  >('breakdown');
  const [userAvailableHours, setUserAvailableHours] = useState<number>(4);
  const [isProcessing, setIsProcessing] = useState(false);
  const [errorMsg, setErrorMsg] = useState<string | null>(null);

  // Result state
  const [result, setResult] = useState<AssignmentBreakdownResponse | null>(null);

  // Modal confirmation state
  const [actionModalOpen, setActionModalOpen] = useState(false);
  const [pendingTaskTitle, setPendingTaskTitle] = useState<string>('');
  const [pendingEstimatedMinutes, setPendingEstimatedMinutes] = useState<number>(45);
  const [isSaving, setIsSaving] = useState(false);

  const selectedAssignment = assignments.find((a) => a.id === selectedAssignmentId);

  const handleRun = async () => {
    if (!selectedAssignment) {
      setErrorMsg('Please select an assignment from your Study Planner.');
      return;
    }

    setErrorMsg(null);
    setIsProcessing(true);

    try {
      const res = await runAssignmentAssistant(
        {
          title: selectedAssignment.title,
          subject: selectedAssignment.subjectName,
          dueDate: selectedAssignment.dueDate,
          notes: selectedAssignment.notes,
          userAvailableHours,
        },
        actionType
      );
      setResult(res);
    } catch (err: any) {
      console.error('Assignment assistant failed:', err);
      setErrorMsg(err.message || 'Failed to process assignment.');
    } finally {
      setIsProcessing(false);
    }
  };

  const handleOpenAddStepModal = (title: string, minutes: number = 45) => {
    setPendingTaskTitle(title);
    setPendingEstimatedMinutes(minutes);
    setActionModalOpen(true);
  };

  const handleConfirmAddTask = async () => {
    if (!pendingTaskTitle) return;
    setIsSaving(true);
    try {
      const proposedAction: AIProposedAction = {
        id: `act_${Date.now()}`,
        type: 'create_task',
        title: `Add Step: ${pendingTaskTitle}`,
        description: `Sub-step for assignment: ${selectedAssignment?.title}`,
        payload: {
          title: `${pendingTaskTitle} (${selectedAssignment?.title || 'Assignment'})`,
          priority: 'medium',
          estimatedMinutes: pendingEstimatedMinutes,
          dueDate: selectedAssignment?.dueDate || new Date().toISOString().split('T')[0],
          notes: `Assignment milestone generated by AI Assignment Assistant.`,
        },
      };

      await executeAIProposedAction(userId, proposedAction);
      setActionModalOpen(false);
      onSuccessToast?.(`Added "${pendingTaskTitle}" to Study Planner tasks!`);
    } catch (err: any) {
      console.error('Failed to create task:', err);
    } finally {
      setIsSaving(false);
    }
  };

  const handleSaveGuide = async () => {
    if (!result || !selectedAssignment) return;
    try {
      await saveUserAIMaterial(userId, {
        id: `mat_${Date.now()}_${Math.random().toString(36).substring(2, 7)}`,
        userId,
        title: `Guide: ${selectedAssignment.title}`,
        category: 'assignment-guide',
        content: result.summary,
        data: result,
        sourceContext: {
          type: 'assignment',
          sourceId: selectedAssignment.id,
          sourceTitle: selectedAssignment.title,
        },
        createdAt: new Date().toISOString(),
        updatedAt: new Date().toISOString(),
      });
      onSuccessToast?.('Saved Assignment Guide to My Study Materials!');
    } catch (err: any) {
      console.error('Failed to save guide:', err);
    }
  };

  return (
    <div className="space-y-6">
      {/* 1. Selector & Config Card */}
      <div className="p-5 rounded-2xl bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 shadow-xs">
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 border-b border-slate-100 dark:border-slate-800 pb-4">
          <div className="flex items-center gap-3">
            <div className="w-10 h-10 rounded-xl bg-indigo-500/10 text-indigo-600 dark:text-indigo-400 flex items-center justify-center">
              <CheckSquare className="w-5 h-5" />
            </div>
            <div>
              <h3 className="text-base font-bold text-slate-900 dark:text-white">
                Assignment Assistant &amp; Scaffolding
              </h3>
              <p className="text-xs text-slate-500 dark:text-slate-400">
                Break complex coursework into sequential checklists, milestones, and structural outlines
              </p>
            </div>
          </div>

          <button
            type="button"
            onClick={handleRun}
            disabled={isProcessing || assignments.length === 0}
            className="inline-flex items-center justify-center gap-2 px-5 py-2.5 rounded-xl bg-indigo-600 hover:bg-indigo-700 text-white font-bold text-xs shadow-xs shadow-indigo-600/30 transition-all cursor-pointer disabled:opacity-40"
          >
            {isProcessing ? (
              <>
                <div className="w-4 h-4 border-2 border-white/30 border-t-white rounded-full animate-spin" />
                <span>Analyzing Assignment...</span>
              </>
            ) : (
              <>
                <Sparkles className="w-4 h-4" />
                <span>Run Assistant</span>
              </>
            )}
          </button>
        </div>

        {/* Disclaimer banner */}
        <div className="mt-3 p-3 rounded-xl bg-slate-50 dark:bg-slate-800/60 border border-slate-200/80 dark:border-slate-700/80 text-[11px] text-slate-600 dark:text-slate-400 flex items-center gap-2">
          <AlertTriangle className="w-4 h-4 text-amber-500 shrink-0" />
          <span>
            Academic Integrity Notice: This tool provides structure, time estimation, and milestone scaffolding. It does not generate original student work or submit assignments.
          </span>
        </div>

        {/* Assignment Selection */}
        {assignments.length === 0 ? (
          <div className="py-6 text-center text-xs text-slate-400">
            No assignments found in Study Planner. Add assignments in the Study Tools tab first.
          </div>
        ) : (
          <div className="grid grid-cols-1 sm:grid-cols-3 gap-4 pt-4 text-xs">
            <div className="sm:col-span-2">
              <label className="block font-semibold text-slate-700 dark:text-slate-300 mb-1.5">
                Select Active Assignment
              </label>
              <select
                value={selectedAssignmentId}
                onChange={(e) => setSelectedAssignmentId(e.target.value)}
                className="w-full py-2 px-3 rounded-lg border border-slate-200 dark:border-slate-700 bg-white dark:bg-slate-800 text-slate-900 dark:text-white font-medium focus:ring-2 focus:ring-indigo-500 focus:outline-hidden cursor-pointer"
              >
                {assignments.map((a) => (
                  <option key={a.id} value={a.id}>
                    {a.title} {a.dueDate ? `(Due: ${a.dueDate})` : ''} {a.subjectName ? `— ${a.subjectName}` : ''}
                  </option>
                ))}
              </select>
            </div>

            <div>
              <label className="block font-semibold text-slate-700 dark:text-slate-300 mb-1.5">
                Goal / Analysis Mode
              </label>
              <select
                value={actionType}
                onChange={(e) => setActionType(e.target.value as any)}
                className="w-full py-2 px-3 rounded-lg border border-slate-200 dark:border-slate-700 bg-white dark:bg-slate-800 text-slate-900 dark:text-white font-medium focus:ring-2 focus:ring-indigo-500 focus:outline-hidden cursor-pointer"
              >
                <option value="breakdown">Full Breakdown &amp; Checklist</option>
                <option value="work-sequence">Sequential Workflow</option>
                <option value="milestones">Target Milestones</option>
                <option value="outline">Draft Structural Outline</option>
                <option value="effort-estimate">Effort &amp; Pacing Estimate</option>
              </select>
            </div>
          </div>
        )}

        {errorMsg && (
          <div className="mt-4 p-3 rounded-xl bg-rose-50 dark:bg-rose-950/40 border border-rose-200 dark:border-rose-900 text-rose-700 dark:text-rose-300 text-xs flex items-center gap-2">
            <AlertTriangle className="w-4 h-4 shrink-0 text-rose-500" />
            <span>{errorMsg}</span>
          </div>
        )}
      </div>

      {/* 2. Results Section */}
      {result && selectedAssignment && (
        <div className="p-6 rounded-2xl bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 shadow-sm space-y-6">
          <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 border-b border-slate-100 dark:border-slate-800 pb-4">
            <div>
              <h3 className="text-base font-bold text-slate-900 dark:text-white">
                {result.assignmentTitle}
              </h3>
              <p className="text-xs text-slate-500 dark:text-slate-400 mt-1">
                {result.summary}
              </p>
            </div>

            <button
              type="button"
              onClick={handleSaveGuide}
              className="inline-flex items-center gap-1.5 px-4 py-2 rounded-xl bg-indigo-50 dark:bg-indigo-950/50 hover:bg-indigo-100 dark:hover:bg-indigo-900 text-indigo-700 dark:text-indigo-300 border border-indigo-200 dark:border-indigo-800 text-xs font-bold transition-colors cursor-pointer shrink-0"
            >
              <Bookmark className="w-4 h-4" />
              <span>Save Guide</span>
            </button>
          </div>

          {/* Effort Estimate Badge */}
          {result.effortEstimate && (
            <div className="grid grid-cols-1 sm:grid-cols-3 gap-3 p-4 rounded-xl bg-slate-50 dark:bg-slate-800/50 border border-slate-200 dark:border-slate-700 text-xs">
              <div>
                <span className="font-semibold text-slate-500 dark:text-slate-400 block">Total Est. Effort:</span>
                <span className="text-sm font-bold text-slate-900 dark:text-white">
                  ~{result.effortEstimate.totalHours} Hours
                </span>
              </div>
              <div>
                <span className="font-semibold text-slate-500 dark:text-slate-400 block">Estimated Difficulty:</span>
                <span className="text-sm font-bold capitalize text-indigo-600 dark:text-indigo-400">
                  {result.effortEstimate.difficultyRating}
                </span>
              </div>
              <div>
                <span className="font-semibold text-slate-500 dark:text-slate-400 block">Pacing Advice:</span>
                <span className="text-xs text-slate-600 dark:text-slate-300">
                  {result.effortEstimate.pacingAdvice}
                </span>
              </div>
            </div>
          )}

          {/* Checklist of Steps */}
          {result.checklist && result.checklist.length > 0 && (
            <div>
              <h4 className="text-xs font-bold text-slate-900 dark:text-white uppercase tracking-wider mb-3 flex items-center gap-1.5">
                <ListOrdered className="w-4 h-4 text-indigo-500" />
                <span>Actionable Step-by-Step Checklist</span>
              </h4>
              <div className="space-y-2.5">
                {result.checklist.map((step) => (
                  <div
                    key={step.id}
                    className="p-3.5 rounded-xl border border-slate-200 dark:border-slate-700/80 bg-white dark:bg-slate-800 flex items-center justify-between gap-4 text-xs"
                  >
                    <div className="space-y-1">
                      <div className="font-bold text-slate-900 dark:text-white flex items-center gap-2">
                        <span className="w-5 h-5 rounded-md bg-indigo-100 dark:bg-indigo-900 text-indigo-700 dark:text-indigo-300 flex items-center justify-center text-[10px] shrink-0 font-mono">
                          {step.stepNumber}
                        </span>
                        <span>{step.title}</span>
                        {step.estimatedMinutes && (
                          <span className="text-[10px] font-mono text-slate-400">
                            ~{step.estimatedMinutes}m
                          </span>
                        )}
                      </div>
                      <p className="text-[11px] text-slate-500 dark:text-slate-400 pl-7">
                        {step.description}
                      </p>
                    </div>

                    <button
                      type="button"
                      onClick={() => handleOpenAddStepModal(step.title, step.estimatedMinutes || 45)}
                      className="inline-flex items-center gap-1 px-3 py-1.5 rounded-lg bg-indigo-50 hover:bg-indigo-100 dark:bg-indigo-950/60 dark:hover:bg-indigo-900 text-indigo-700 dark:text-indigo-300 font-semibold text-xs transition-colors shrink-0 cursor-pointer"
                    >
                      <Plus className="w-3.5 h-3.5" />
                      <span>Add as Task</span>
                    </button>
                  </div>
                ))}
              </div>
            </div>
          )}

          {/* Milestones */}
          {result.suggestedMilestones && result.suggestedMilestones.length > 0 && (
            <div>
              <h4 className="text-xs font-bold text-slate-900 dark:text-white uppercase tracking-wider mb-3 flex items-center gap-1.5">
                <Calendar className="w-4 h-4 text-purple-500" />
                <span>Suggested Timeline Milestones</span>
              </h4>
              <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
                {result.suggestedMilestones.map((ms, idx) => (
                  <div
                    key={idx}
                    className="p-3 rounded-xl border border-slate-200 dark:border-slate-700 bg-slate-50/50 dark:bg-slate-800/40 text-xs space-y-1"
                  >
                    <div className="font-bold text-slate-900 dark:text-white flex items-center justify-between">
                      <span>{ms.title}</span>
                      <span className="text-[10px] text-purple-600 dark:text-purple-400 font-semibold">
                        {ms.targetDaysBeforeDue} days before due
                      </span>
                    </div>
                    <p className="text-[11px] text-slate-500 dark:text-slate-400">
                      Deliverable: {ms.deliverable}
                    </p>
                  </div>
                ))}
              </div>
            </div>
          )}

          {/* Draft Outline */}
          {result.outline && (
            <div>
              <h4 className="text-xs font-bold text-slate-900 dark:text-white uppercase tracking-wider mb-2 flex items-center gap-1.5">
                <FileText className="w-4 h-4 text-emerald-500" />
                <span>Suggested Structural Outline</span>
              </h4>
              <div className="p-4 rounded-xl bg-slate-50 dark:bg-slate-800/60 border border-slate-200 dark:border-slate-700 text-xs font-mono text-slate-800 dark:text-slate-200 whitespace-pre-wrap leading-relaxed">
                {result.outline}
              </div>
            </div>
          )}
        </div>
      )}

      {/* Confirmation Modal */}
      {actionModalOpen && (
        <AIActionConfirmationModal
          isOpen={actionModalOpen}
          action={{
            id: `act_${Date.now()}`,
            type: 'create_task',
            title: `Add Assignment Task: ${pendingTaskTitle}`,
            description: `Create a concrete task in Study Planner for "${selectedAssignment?.title}".`,
            payload: {
              title: pendingTaskTitle,
              subjectName: selectedAssignment?.subjectName,
              dueDate: selectedAssignment?.dueDate,
              estimatedMinutes: pendingEstimatedMinutes,
              priority: 'medium',
            },
          }}
          onConfirm={handleConfirmAddTask}
          onCancel={() => setActionModalOpen(false)}
          isExecuting={isSaving}
        />
      )}
    </div>
  );
};
